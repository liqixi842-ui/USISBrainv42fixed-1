/**
 * 获取友好的错误消息
 * @param {Error} error - 错误对象
 * @returns {string} 友好的错误消息
 */
function getFriendlyErrorMessage(error) {
  const message = error.message.toLowerCase();
  
  if (message.includes('file too large') || message.includes('too big')) {
    return 'PDF file too large (>50MB). Please try a shorter report or text format.';
  }
  
  if (message.includes('timeout')) {
    return 'Upload timeout. Please check your network connection and try again.';
  }
  
  if (message.includes('forbidden') || message.includes('403')) {
    return 'Bot lacks permission to send files. Please check bot settings.';
  }
  
  if (message.includes('not found') || message.includes('404')) {
    return 'Chat not found. Please start the bot first.';
  }
  
  // 默认错误
  return `Failed to send PDF: ${error.message}`;
}

/**
 * 保存 PDF 到临时文件（用于调试）
 * @param {Buffer} pdfBuffer - PDF Buffer
 * @param {string} filename - 文件名
 * @returns {string} 保存的文件路径
 */
function savePdfToTempFile(pdfBuffer, filename) {
  const tempDir = path.join(__dirname, '..', 'tmp');
  
  // 创建 tmp 目录（如果不存在）
  if (!fs.existsSync(tempDir)) {
    fs.mkdirSync(tempDir, { recursive: true });
  }
  
  const filePath = path.join(tempDir, filename);
  fs.writeFileSync(filePath, pdfBuffer);
  
  console.log(`💾 [TelegramPdf] PDF saved to: ${filePath}`);
  return filePath;
}

