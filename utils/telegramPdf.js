const fs = require('fs');
const path = require('path');

/**
 * 发送 PDF 文档到 Telegram
 * @param {number} chatId - 聊天 ID
 * @param {Buffer} pdfBuffer - PDF Buffer
 * @param {string} filename - 文件名（如 NVDA_Equity_Research_USISv7.pdf）
 * @param {string} caption - 说明文字
 * @param {Object} bot - Telegram Bot 实例
 * @returns {Promise<Object>} Telegram API 响应
 */
async function sendPdfReport(chatId, pdfBuffer, filename, caption, bot) {
  console.log(`\n📤 [TelegramPdf] Sending PDF document`);
  console.log(`   ├─ Chat ID: ${chatId}`);
  console.log(`   ├─ Filename: ${filename}`);
  console.log(`   ├─ Size: ${(pdfBuffer.length / 1024).toFixed(2)} KB`);
  console.log(`   └─ Caption: ${caption.substring(0, 50)}...`);
  
  try {
    // 验证输入
    if (!pdfBuffer || !Buffer.isBuffer(pdfBuffer)) {
      throw new Error('Invalid PDF buffer provided');
    }
    
    if (pdfBuffer.length === 0) {
      throw new Error('PDF buffer is empty');
    }
    
    if (pdfBuffer.length > 50 * 1024 * 1024) {
      throw new Error('PDF too large (>50MB). Telegram limit exceeded.');
    }
    
    // 发送文档（使用 Buffer）
    const result = await bot.sendDocument(
      chatId,
      pdfBuffer,
      {
        caption: caption,
        parse_mode: 'Markdown'
      },
      {
        filename: filename,
        contentType: 'application/pdf'
      }
    );
    
    console.log(`✅ [TelegramPdf] PDF sent successfully`);
    console.log(`   └─ Message ID: ${result.message_id}\n`);
    
    return result;
    
  } catch (error) {
    console.error(`\n❌ [TelegramPdf] Failed to send PDF`);
    console.error(`   ├─ Error: ${error.message}`);
    console.error(`   └─ Stack: ${error.stack.substring(0, 200)}...\n`);
    
    // 更友好的错误消息
    const errorMessage = getFriendlyErrorMessage(error);
    throw new Error(errorMessage);
  }
}

/**
 * 生成 PDF 文件名
 * @param {string} symbol - 股票代码
 * @param {string} language - 语言
 * @returns {string} 文件名
 */
function generatePdfFilename(symbol, language = 'en') {
  const timestamp = new Date().toISOString().split('T')[0]; // YYYY-MM-DD
  const langSuffix = language !== 'en' ? `_${language.toUpperCase()}` : '';
  return `${symbol.toUpperCase()}_Equity_Research_USISv7${langSuffix}_${timestamp}.pdf`;
}

